#include "common.h"

/* guTranslate (Hudson) */
void func_800A4F30(Mtx* m, Vec3f* t) {
    s32 e1;
    s32 e2;
    s32 e3;

    e1 = t->x * 65536.0f;
    e2 = t->y * 65536.0f;
    e3 = t->z * 65536.0f;
    m->m[0][0] = 0x10000;
    m->m[0][1] = 0;
    m->m[0][2] = 1;
    m->m[0][3] = 0;
    m->m[1][0] = 0;
    m->m[1][1] = 0x10000;
    m->m[1][2] = (e1 & 0xFFFF0000) | ((e2 >> 16) & 0xFFFF);
    m->m[1][3] = (e3 & 0xFFFF0000) | 1;
    m->m[2][0] = 0;
    m->m[2][1] = 0;
    m->m[2][2] = 0;
    m->m[2][3] = 0;
    m->m[3][0] = 0;
    m->m[3][1] = 0;
    m->m[3][2] = ((e1 << 16) & 0xFFFF0000) | (u16)e2;
    m->m[3][3] = (e3 << 16) & 0xFFFF0000;
}
